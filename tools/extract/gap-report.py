#!/usr/bin/env python3
"""gap-report.py -- what charon translated for a crate but aeneas did not emit.

Reads the crate's LLBC (charon's output) and hax's log of the run, and prints a
TOML report that extract.sh installs as crates/<crate>/extraction/gaps.toml:

  - [charon]: the errors charon reported, and where (a `Type error after
    transformations` in core's own code is still listed);
  - [[dropped]]: every function or constant of this crate that charon
    translated with a body but left out of `ordered_decls`. aeneas emits only what that list
    orders, so each one is silently missing from the generated Lean
    (docs/extractor-issues.md, 4). A dropped item the model needs is transcribed
    by hand and has a `[[mirror]]` entry; tools/status.py cross-checks them.

The report is deterministic, so `extract.sh --check` requires it to reproduce
byte for byte like the generated Lean.

  gap-report.py <crate dir> <llbc> <hax log>
"""
import json
import re
import sys
from pathlib import Path

ANSI = re.compile(r"\x1b\[[0-9;]*m")


def load(llbc):
    return json.loads(Path(llbc).read_text())["translated"]


def names(d):
    return {(next(iter(e["key"])), next(iter(e["key"].values()))): e["value"]
            for e in d["item_names"]}


def ordered_ids(d):
    """Every (kind, id) that appears in ordered_decls, whatever its grouping."""
    out = set()
    kinds = ("Fun", "Global", "Type", "TraitDecl", "TraitImpl")

    def walk(x, kind=None):
        if isinstance(x, int):
            if kind:
                out.add((kind, x))
        elif isinstance(x, dict):
            for k, v in x.items():
                walk(v, k if k in kinds else kind)
        elif isinstance(x, list):
            for y in x:
                walk(y, kind)
    walk(d["ordered_decls"])
    return out


def render(d, nm, kind, i):
    """The item's path, with an impl rendered as `{impl <trait>}` or `{impl}`."""
    parts = []
    for c in nm.get((kind, i), []):
        if "Ident" in c:
            parts.append(c["Ident"][0])
        elif "Impl" in c:
            imp = c["Impl"]
            if "Trait" in imp:
                ti = d["trait_impls"][imp["Trait"]]
                tid = ti["impl_trait"]["id"] if ti else None
                trait = "::".join(x["Ident"][0] for x in nm.get(("TraitDecl", tid), [])
                                  if "Ident" in x)
                parts.append("{impl " + trait + "}")
            else:
                parts.append("{impl}")
    return "::".join(parts)


def source(d, meta):
    span = meta.get("span", {}).get("data")
    if not span:
        return ""
    f = d["files"][span["file_id"]]["name"]
    path = f.get("Local") or f.get("Virtual") or str(f)
    return f"{path}:{span['beg']['line']}"


def charon_errors(log):
    """(count, sorted unique sites) of the `error:` diagnostics charon printed."""
    text = ANSI.sub("", Path(log).read_text(errors="replace")).splitlines()
    sites, n = set(), 0
    for k, line in enumerate(text):
        if line.startswith("error: Type error") or line.startswith("error: Item ") \
                or (line.startswith("error:") and "hax:" not in line and "could not compile" not in line):
            n += 1
            for nxt in text[k + 1:k + 40]:
                m = re.match(r"\s*--> (\S+)", nxt)
                if m:
                    site = re.sub(r"^/rustc/[0-9a-f]*/?", "", m.group(1))
                    site = re.sub(r"^.*?/library/", "library/", site)
                    sites.add(site)
                    break
    return n, sorted(sites)


def q(s):
    return json.dumps(s, ensure_ascii=False)


def main(argv):
    if len(argv) != 3:
        sys.exit(__doc__)
    crate_dir, llbc, log = argv
    d = load(llbc)
    nm = names(d)
    ordered = ordered_ids(d)
    crate = d["crate_name"]
    dropped = []
    for kind, decls in (("Fun", d["fun_decls"]), ("Global", d["global_decls"])):
        for i, decl in enumerate(decls):
            if not decl or (kind, i) in ordered:
                continue
            meta = decl["item_meta"]
            if not meta.get("is_local"):
                continue
            if kind == "Fun" and not decl.get("body"):
                continue
            item = render(d, nm, kind, i)
            # Drop glue and closure impls are compiler artifacts of their parent
            # item, which is listed in its own right.
            if "drop_glue" in item or "::closure" in item \
                    or "{impl core::ops::function::Fn" in item:
                continue
            dropped.append((item, source(d, meta)))
    # A constant appears twice, as a global and as its initializer.
    dropped = sorted(set(dropped))
    n_err, sites = charon_errors(log)

    print(f"# Generated by tools/extract/gap-report.py from the last extraction of {Path(crate_dir).name}.")
    print("# Do not edit: extract.sh rewrites it, and `--check` requires it unchanged.")
    print()
    print("[charon]")
    print(f"crate  = {q(crate)}")
    print(f"errors = {n_err}")
    print("error_sites = [" + ", ".join(q(s) for s in sites) + "]")
    for item, src in dropped:
        print()
        print("[[dropped]]  # translated with a body, not in ordered_decls: aeneas does not emit it")
        print(f"item   = {q(item)}")
        print(f"source = {q(src)}")


if __name__ == "__main__":
    main(sys.argv[1:])
